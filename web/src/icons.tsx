export function ChannelIcon({ channel }: { channel: string }) {
  if (channel.startsWith("email")) return <MailIcon size={13} />;
  if (channel === "teams" || channel === "slack") return <ChatIcon size={13} />;
  if (channel === "manual") return <PenIcon size={13} />;
  if (channel === "mcp") return <BotIcon size={13} />;
  return <PlugIcon size={13} />;
}
