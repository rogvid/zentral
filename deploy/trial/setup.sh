#!/usr/bin/env bash
# Set up and start a Zentral trial on this host.
#
#   ./setup.sh                       # hostname: <this host's public IP>.sslip.io
#   ./setup.sh desk.example.com      # your own DNS name (A record → this host)
#   ./setup.sh --no-start [host]     # write .env only
#
# Needs: Docker Engine with the Compose plugin, openssl, and ports 80 and 443
# reachable from the internet (for the automatic certificate).
set -euo pipefail
cd "$(dirname "$0")"

start=1
host=""
for arg in "$@"; do
  case "$arg" in
    --no-start) start=0 ;;
    -h | --help) sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "unknown option: $arg" >&2; exit 2 ;;
    *) host="$arg" ;;
  esac
done

command -v docker >/dev/null || { echo "Docker is not installed: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "The Docker Compose plugin is missing." >&2; exit 1; }
command -v openssl >/dev/null || { echo "openssl is not installed." >&2; exit 1; }

if [[ -e .env ]]; then
  echo ".env already exists — this trial is set up. Start it with: docker compose up -d" >&2
  echo "(To start over with an empty database: docker compose down -v && rm .env && ./setup.sh)" >&2
  exit 1
fi

if [[ -z "$host" ]]; then
  ip=$(curl -fsS4 --max-time 5 https://api.ipify.org || curl -fsS4 --max-time 5 https://ifconfig.me || true)
  if [[ ! "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "Could not detect this host's public IPv4 address. Pass a hostname: ./setup.sh desk.example.com" >&2
    exit 1
  fi
  # sslip.io resolves <ip>.sslip.io to <ip>, so Caddy can get a real certificate without DNS setup.
  host="$ip.sslip.io"
fi

rand() { openssl rand -base64 "$1" | tr -d '\n'; }
fernet_key=$(openssl rand -base64 32 | tr '+/' '-_')        # 32 bytes, url-safe base64
trial_password=$(rand 18 | tr '+/' 'xy')
echo "Hashing the trial password (pulls the Caddy image once)…"
password_hash=$(docker run --rm caddy:2-alpine caddy hash-password --plaintext "$trial_password")

umask 077
cat > .env <<EOF
# Zentral trial — generated by setup.sh. Contains secrets: keep it private.
# Anyone who can read this file can read all data in the trial.

ZENTRAL_HOSTNAME=$host
POSTGRES_PASSWORD=$(rand 24 | tr '+/' 'xy')

# Password in front of the persona sign-in (the plain text is not stored).
TRIAL_USER=trial
TRIAL_PASSWORD_HASH='$password_hash'

# Encryption keys in plain text: fine for a trial with made-up data, not for
# real data (docs/operations/key-custody.md).
ZENTRAL_KEY_PROVIDER=env
ZENTRAL_ENCRYPTION_KEYS=$fernet_key
ZENTRAL_BLIND_INDEX_KEY=$(rand 48)
ZENTRAL_AUDIT_HMAC_KEY=$(rand 48)

# AI classification. rules = keyword matching, nothing leaves the host.
ZENTRAL_AI_PROVIDER=rules
# ZENTRAL_AI_PROVIDER=openai_compatible
# ZENTRAL_AI_BASE_URL=http://your-model-server:11434/v1
# ZENTRAL_AI_MODEL=llama3.1:8b

# Released image instead of building here (faster on a small VPS):
# ZENTRAL_IMAGE=ghcr.io/rogvid/zentral@sha256:<digest from the release notes>
EOF
echo "Wrote .env (mode 600)."

if (( start )); then
  docker compose up -d --build
  echo "Waiting for Zentral to become healthy…"
  for _ in $(seq 60); do
    if [[ "$(docker inspect -f '{{.State.Health.Status}}' "$(docker compose ps -q api)" 2>/dev/null)" == healthy ]]; then
      break
    fi
    sleep 2
  done
  docker compose run --rm --no-deps api doctor || true
fi

cat <<EOF

  Zentral trial
  ─────────────
  URL       https://$host
  Sign-in   user: trial   password: $trial_password
            (asked for when you pick a persona — save it now, it is not stored)

  Sample data     docker compose run --rm seed
  Logs            docker compose logs -f api worker caddy
  Stop / start    docker compose stop / docker compose up -d
  Remove all      docker compose down -v

EOF
(( start )) || echo "  Start it with: docker compose up -d --build"
