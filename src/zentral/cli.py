@app.command()
def serve(
    host: str = "127.0.0.1",
    port: int = 8000,
    proxy_headers: bool = typer.Option(
        False, help="Trust X-Forwarded-* from the addresses in --forwarded-allow-ips."
    ),
    forwarded_allow_ips: str = "127.0.0.1",
) -> None:
    """Run the API, MCP endpoint and web client."""
    import uvicorn

    from zentral.security.keys import materialise

    # Fail before binding the port; the server process unwraps again for itself.
    materialise(get_settings()).validate_for_runtime()
    uvicorn.run(
        "zentral.api.app:create_app",
        factory=True,
        host=host,
        port=port,
        proxy_headers=proxy_headers,
        forwarded_allow_ips=forwarded_allow_ips,
        server_header=False,
        access_log=False,  # Zentral writes its own access log without query strings
        log_config=None,
    )


@app.command()
def doctor() -> None:
    """Check that this installation is configured correctly. Exit code 1 on failure."""
    from zentral.doctor import run_checks

    try:
        settings = get_settings()
    except Exception as exc:
        typer.echo(f"✗ configuration: {type(exc).__name__}: could not read settings", err=True)
        raise typer.Exit(1) from None
    results = asyncio.run(run_checks(settings))
    marks = {"ok": "✓", "warn": "!", "fail": "✗"}
    for result in results:
        typer.echo(f"{marks[result.status]} {result.name}: {result.detail}")
    failed = sum(r.status == "fail" for r in results)
    warned = sum(r.status == "warn" for r in results)
    typer.echo(f"\n{len(results) - failed - warned} ok, {warned} warning(s), {failed} failure(s)")
    if failed:
        raise typer.Exit(1)


@app.command()
def init(
    output: Path = typer.Option(Path(".env"), help="File to write."),
    auth: str = typer.Option("entra", help="entra, oidc or dev"),
    force: bool = typer.Option(False, help="Overwrite an existing file."),
) -> None:
    """Write a starter configuration file with freshly generated keys."""
    from zentral.security.crypto import generate_key

    if auth not in ("entra", "oidc", "dev"):
        raise typer.BadParameter("auth must be entra, oidc or dev")
    if output.exists() and not force:
        typer.echo(f"{output} already exists (use --force to overwrite)", err=True)
        raise typer.Exit(1)
    identity = {
        "entra": (
            "ZENTRAL_ENTRA_TENANT_ID=\nZENTRAL_ENTRA_API_CLIENT_ID=\nZENTRAL_ENTRA_SPA_CLIENT_ID=\n"
        ),
        "oidc": (
            "ZENTRAL_OIDC_ISSUER=\n"
            "ZENTRAL_OIDC_AUDIENCES=\n"
            "ZENTRAL_OIDC_CLIENT_ID=\n"
            "# ZENTRAL_OIDC_ROLES_CLAIM=realm_access.roles\n"
            "# ZENTRAL_ROLE_MAP=servicedesk-admins=Zentral.Admin,servicedesk-agents=Zentral.Agent\n"
        ),
        "dev": "# Development sign-in: never expose this instance to a network.\n",
    }[auth]
    production = auth != "dev"
    keys_block_production = (
        "\n# --- keys: a keyring wrapped by your KMS (docs/operations/key-custody.md) ---\n"
        "# Fill in, then create the keyring with `zentral keys init`.\n"
        "ZENTRAL_KEY_PROVIDER=azure_keyvault\n"
        "ZENTRAL_AZURE_KEYVAULT_KEY_ID=\n"
        "# ZENTRAL_KEY_PROVIDER=vault_transit\n"
        "# ZENTRAL_VAULT_ADDR=\n"
        "# ZENTRAL_VAULT_TRANSIT_KEY=zentral\n"
        "ZENTRAL_KEYRING_FILE=/etc/zentral/keys/keyring.json\n"
    )
    keys_block_development = (
        "\n# --- keys (plain text: development only) ---\n"
        f"ZENTRAL_ENCRYPTION_KEYS={generate_key()}\n"
        f"ZENTRAL_BLIND_INDEX_KEY={secrets.token_urlsafe(48)}\n"
        f"ZENTRAL_AUDIT_HMAC_KEY={secrets.token_urlsafe(48)}\n"
    )
    base_url = "https://servicedesk.example.com" if production else "http://localhost:8000"
    hosts = "servicedesk.example.com" if production else "localhost,127.0.0.1"
    lines = (
        "# Zentral configuration — generated by `zentral init`.\n"
        "# This file contains secrets: keep it out of version control (chmod 600).\n"
        "# Reference: docs/operations/configuration.md\n\n"
        f"ZENTRAL_ENV={'production' if production else 'development'}\n"
        f"ZENTRAL_PUBLIC_BASE_URL={base_url}\n"
        f"ZENTRAL_ALLOWED_HOSTS={hosts}\n"
        "ZENTRAL_DATABASE_URL="
        + (
            "postgresql+asyncpg://zentral:CHANGE-ME@db:5432/zentral\n"
            if production
            else "sqlite+aiosqlite:///./zentral-dev.db\n"
        )
        + f"\n# --- identity ---\nZENTRAL_AUTH_MODE={auth}\n{identity}"
        + (keys_block_production if production else keys_block_development)
        + "\n# --- AI classification (rules = no model, nothing leaves the process) ---\n"
        "ZENTRAL_AI_PROVIDER=rules\n"
        "# ZENTRAL_AI_PROVIDER=openai_compatible\n"
        "# ZENTRAL_AI_BASE_URL=http://ollama:11434/v1\n"
        "# ZENTRAL_AI_MODEL=llama3.1:8b\n"
    )
    output.touch(mode=0o600, exist_ok=True)
    output.chmod(0o600)
    output.write_text(lines, encoding="utf-8")
    typer.echo(f"wrote {output} (mode 600). Fill in the blanks, then run `zentral doctor`.")


@app.command()
def worker() -> None:
    """Run the background worker (classification, polling, delivery, retention)."""
    from zentral.logging import configure_logging
    from zentral.runtime import build_runtime
    from zentral.services.jobs import Worker

    async def main() -> None:
        settings = get_settings()
        configure_logging(settings.log_level)
        runtime = build_runtime(settings)
        stop = asyncio.Event()
        loop = asyncio.get_running_loop()
        for sig in (signal.SIGINT, signal.SIGTERM):
            loop.add_signal_handler(sig, stop.set)
        try:
            await Worker(runtime).run_forever(stop)
        finally:
            await runtime.aclose()

    asyncio.run(main())


